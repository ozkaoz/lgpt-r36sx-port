/*
 * input_policy_host_test.cpp -- F1: verificacion host del catalogo dorado
 * de input del port (ActionMap + ChordResolver).
 *
 * Compila sin dependencias de la app: g++ -std=gnu++03 -Wall -Wextra -Werror
 *   ChordResolver.cpp ActionMap.cpp input_policy_host_test.cpp
 *
 * Cada assertion es una transcripcion del comportamiento del codigo dorado
 * (SampleChopperModal.cpp ProcessButtonMask, MixerView.cpp ProcessButtonMask,
 * AppWindow.cpp onEvent/SynchronizeInputMask en Bacon 1.2.1). Si falla,
 * ALGUIEN CAMBIO EL COMPORTAMIENTO o el catalogo no lo transcribe.
 */
#include <stdio.h>
#include "Application/UI/Input/ChordResolver.h"

using namespace UI::Input;

static int g_failures = 0;

#define CHECK(cond) do { \
    if (!(cond)) { \
        printf("FAIL %s:%d: %s\n", __FILE__, __LINE__, #cond); \
        ++g_failures; \
    } \
} while (0)

#define EXPECT_ACTION(mask_, ctx_, action_) do { \
    ActionId got = ChordResolver_Resolve((mask_), (ctx_)); \
    if (got != (action_)) { \
        printf("FAIL %s:%d: mask=0x%04x ctx=%d esperaba %d got %d\n", \
               __FILE__, __LINE__, (unsigned)(mask_), (int)(ctx_), \
               (int)(action_), (int)got); \
        ++g_failures; \
    } \
} while (0)

static void test_global(void) {
    EXPECT_ACTION(KEY_SELECT | KEY_R1, CTX_GLOBAL, ACTION_OPEN_HELP);
    EXPECT_ACTION(KEY_SELECT | KEY_R1 | KEY_A, CTX_GLOBAL, ACTION_OPEN_HELP);
    EXPECT_ACTION(KEY_SELECT | KEY_R2, CTX_GLOBAL, ACTION_OPEN_AUDIO_DRIVER);
    EXPECT_ACTION(KEY_L1 | KEY_X, CTX_GLOBAL, ACTION_UNDO);
    EXPECT_ACTION(KEY_R1 | KEY_X, CTX_GLOBAL, ACTION_REDO);
    /* L1+R1+X: la tabla no lo resuelve (regla V16 de AppWindow). */
    EXPECT_ACTION(KEY_L1 | KEY_R1 | KEY_X, CTX_GLOBAL, ACTION_NONE);
    EXPECT_ACTION(KEY_L1, CTX_GLOBAL, ACTION_NONE);
    EXPECT_ACTION(KEY_A | KEY_B, CTX_GLOBAL, ACTION_NONE);
    printf("global: help/audio/undo/redo OK\n");
}

