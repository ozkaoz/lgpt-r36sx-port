    EXPECT_ACTION(KEY_A | KEY_LEFT, CTX_CHOPPER_TRIM, ACTION_NUDGE_START_LEFT);
    EXPECT_ACTION(KEY_L1 | KEY_A | KEY_RIGHT, CTX_CHOPPER_TRIM, ACTION_NUDGE_START_RIGHT_COARSE);
    EXPECT_ACTION(KEY_B | KEY_LEFT, CTX_CHOPPER_TRIM, ACTION_NUDGE_END_LEFT);
    EXPECT_ACTION(KEY_L1 | KEY_B | KEY_RIGHT, CTX_CHOPPER_TRIM, ACTION_NUDGE_END_RIGHT_COARSE);
